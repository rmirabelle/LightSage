import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('./web/app.js',import.meta.url),'utf8');
const cacheCode=source.slice(source.indexOf('const lightDetailsCache ='),source.indexOf('async function showLightDetails('));
const stored=new Map();
const localStorage={getItem:key=>stored.get(key)??null,setItem:(key,value)=>stored.set(key,value)};
const first=vm.createContext({localStorage}); vm.runInContext(cacheCode,first);
const partial={nodeId:'1',fields:{productName:'H6013'},addresses:[],partial:true};
first.cacheLightDetails('1',partial);
const reopened=vm.createContext({localStorage}); vm.runInContext(cacheCode,reopened);
assert.equal(reopened.cachedLightDetails('1').fields.productName,'H6013');
assert.equal(reopened.cachedLightDetails('1').partial,true);
assert.equal(reopened.cachedLightDetails('2'),undefined);
stored.set('lightsage-details:2','broken');
assert.equal(reopened.cachedLightDetails('2'),undefined);
stored.set('lightsage-details:2',JSON.stringify(partial));
assert.equal(reopened.cachedLightDetails('2'),undefined,'Wrong device ID is ignored');
console.log('PASS: phone cache survives reopening, retains partial details and rejects corrupt/mismatched entries.');
